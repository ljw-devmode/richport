
<h3>개인정보 처리방침</h3>
<br/>
<br/>
<b>제 1 조 개인정보의 수집 및 이용 목적</b><br/>
<br/>
회사가 수집한 개인정보는 다음의 목적을 위해 활용합니다.<br/>
<br/>
1. 서비스 제공에 관한 계약 이행 및 서비스 제공에 따른 요금 정산<br/>
콘텐츠 제공, 물품 배송, 청구서 발송, 본인 인증, 요금 결제, 요금 추심 등<br/>
<br/>
2. 회원 관리<br/>
회원제 서비스 이용에 따른 본인 확인, 개인 식별, 가입 의사 확인, 가입 및 가입 횟수 제한, 14세 미만 가입자의 법정 대리인 본인 확인, 분쟁 조정을 위한 기록 보존, 불만 처리 등 민원 처리, 고지 사항 전달<br/>
<br/>
3. 마케팅 및 광고에 활용<br/>
신규 서비스 및 제품 개발, 인구통계학적 특성에 따른 서비스 제공 및 광고 게재, 접속 빈도 파악, 회원의 서비스 이용에 대한 통계, 이벤트 등 광고성 정보 전달 (회원의 개인정보는 광고를 의뢰하는 제 3자에게 제공되지 않습니다.)<br/>
<br/>
<br/>
<b>제 2 조 수집하는 개인정보 항목 및 수집 방법</b><br/>
<br/>
[수집하는 개인정보 항목]<br/>
1. 최초 회원 가입 시 회원 식별 및 최적화된 서비스 제공을 위해 아래와 같은 정보를 수집합니다.<br/>
- 필수 항목: 이름, 기업명, 이메일 주소, 전화번호, 가입 인증 정보<br/>
<br/>
2. 개인정보 수정 시 서비스 이용 편의를 위해 회원이 자발적으로 아래와 같은 정보를 제공할 수 있습니다.<br/>
- 주소, 전화번호(서비스 운영상 필수 정보 확보)<br/>
<br/>
3. 서비스 이용 과정이나 이벤트 응모 과정, 기타 사업 처리 과정에서 아래와 같은 정보가 생성되어 수집될 수 있습니다.<br/>
- 성명, 실명 인증값, 아이핀 번호(아이핀 인증 시), 성별, 생년월일, 직업, 회사명, 주소, 전화번호, 서비스 이용 기록, 접속 로그, 쿠키, 접속 IP 정보, 결제 기록, 불량 이용 기록, 이용자 상태 정보, 방문 일시 등<br/>
<br/>
[수집 방법]<br/>
회사는 다음과 같은 방법으로 개인정보를 수집합니다.<br/>
<br/>
1. 홈페이지 또는 클라우드 문서를 통한 회원 가입, 게시판, 이벤트 응모<br/>
<br/>
2. 서비스 사용 중 이용자의 자발적 제공을 통한 수집<br/>
<br/>
<br/>
<b>제 3 조 개인정보의 보유 및 이용 기간</b><br/>
<br/>
원칙적으로 개인정보 수집 및 이용 목적이 달성된 후에는 해당 정보를 지체 없이 파기합니다.<br/>
단, 다음의 정보에 대해서는 아래의 이유로 명시한 기간 동안 보존합니다.<br/>
<br/>
1. 회원 탈퇴 시 보존 개인정보<br/>
- 보존 항목: 회원이 제공한 이름, 사업자 등록 번호, 아이디, 이메일 주소, 휴대 전화 번호 등<br/>
- 보존 근거: 불량 이용자의 재가입 방지, 명예 훼손 등 권리 침해 분쟁 및 수사 협조<br/>
- 보존 기간: 회원 탈퇴 후 1년<br/>
<br/>
2. 상법, 전자상거래 등에서의 소비자 보호에 관한 법률 등 관계 법령의 규정에 의하여 보존할 필요가 있는 경우 회사는 관계 법령에서 정한 일정한 기간 동안 회원 정보를 보관합니다. 이 경우 회사는 보관하는 정보를 그 보관의 목적으로만 이용하며, 보존 기간은 아래와 같습니다.<br/>
- 계약 또는 청약 철회 등에 관한 기록<br/>
  ㆍ보존 이유: 전자상거래 등에서의 소비자 보호에 관한 법률<br/>
  ㆍ보존 기간: 3년<br/>
<br/>
- 대금 결제 및 재화 등의 공급에 관한 기록<br/>
  ㆍ보존 이유: 전자상거래 등에서의 소비자 보호에 관한 법률<br/>
  ㆍ보존 기간: 3년<br/>
<br/>
- 소비자의 불만 또는 분쟁 처리에 관한 기록<br/>
  ㆍ보존 이유: 전자상거래 등에서의 소비자 보호에 관한 법률<br/>
  ㆍ보존 기간: 3년<br/>
<br/>
- 방문에 관한 기록(서비스 이용 기록, 접속 로그, 접속 IP 정보 등)<br/>
  ㆍ보존 이유: 통신비밀보호법<br/>
  ㆍ보존 기간: 3년<br/>
