
<h3>Chính sách bảo mật</h3>
<br/>
<br/>
<b>Điều 1. Mục đích thu thập và sử dụng thông tin cá nhân</b><br/>
<br/>
Thông tin cá nhân do Công ty thu thập được sử dụng cho các mục đích sau.<br/>
<br/>
1. Thực hiện hợp đồng cung cấp dịch vụ và thanh toán phí theo dịch vụ được cung cấp<br/>
Cung cấp nội dung, giao hàng, gửi hóa đơn, xác minh danh tính, thanh toán phí, thu phí, v.v.<br/>
<br/>
2. Quản lý thành viên<br/>
Xác minh danh tính khi sử dụng dịch vụ dành cho thành viên, nhận dạng cá nhân, xác nhận ý định đăng ký, giới hạn việc đăng ký và số lần đăng ký, xác minh người đại diện theo pháp luật của người đăng ký dưới 14 tuổi, lưu giữ hồ sơ để giải quyết tranh chấp, xử lý khiếu nại và các yêu cầu khác, gửi thông báo<br/>
<br/>
3. Sử dụng cho mục đích tiếp thị và quảng cáo<br/>
Phát triển dịch vụ và sản phẩm mới, cung cấp dịch vụ và đăng quảng cáo theo đặc điểm nhân khẩu học, xác định tần suất truy cập, thống kê việc sử dụng dịch vụ của thành viên, gửi thông tin quảng cáo như sự kiện, v.v. (Thông tin cá nhân của thành viên sẽ không được cung cấp cho bên thứ ba yêu cầu quảng cáo.)<br/>
<br/>
<br/>
<b>Điều 2. Các loại thông tin cá nhân được thu thập và phương thức thu thập</b><br/>
<br/>
[Các loại thông tin cá nhân được thu thập]<br/>
1. Khi sử dụng dịch vụ, chúng tôi thu thập các thông tin sau để nhận dạng thành viên và cung cấp dịch vụ tối ưu.<br/>
- Thông tin bắt buộc: Tên doanh nghiệp, họ tên, địa chỉ email, số điện thoại, thông tin xác thực đăng ký<br/>
<br/>
2. Khi chỉnh sửa thông tin cá nhân, thành viên có thể tự nguyện cung cấp các thông tin sau để thuận tiện cho việc sử dụng dịch vụ.<br/>
- Địa chỉ, số điện thoại (thông tin cần thiết cho việc vận hành dịch vụ)<br/>
<br/>
3. Trong quá trình sử dụng dịch vụ, tham gia sự kiện hoặc các hoạt động kinh doanh khác, các thông tin sau có thể được tạo ra và thu thập.<br/>
- Họ tên, giá trị xác thực tên thật, số i-PIN (khi xác thực bằng i-PIN), giới tính, ngày sinh, nghề nghiệp, tên công ty, địa chỉ, số điện thoại, lịch sử sử dụng dịch vụ, nhật ký truy cập, cookie, thông tin IP truy cập, lịch sử thanh toán, lịch sử sử dụng sai quy định, thông tin trạng thái người dùng, thời gian truy cập, v.v.<br/>
<br/>
[Phương thức thu thập]<br/>
Công ty thu thập thông tin cá nhân bằng các phương thức sau.<br/>
<br/>
1. Đăng ký thành viên, bảng tin, tham gia sự kiện thông qua trang web hoặc dịch vụ của Công ty<br/>
<br/>
2. Thu thập thông qua việc người dùng tự nguyện cung cấp trong quá trình sử dụng dịch vụ<br/>
<br/>
<br/>
<b>Điều 3. Thời gian lưu giữ và sử dụng thông tin cá nhân</b><br/>
<br/>
Về nguyên tắc, sau khi đạt được mục đích thu thập và sử dụng thông tin cá nhân, thông tin đó sẽ được hủy ngay lập tức.<br/>
Tuy nhiên, các thông tin sau đây sẽ được lưu giữ trong thời hạn nêu rõ vì những lý do dưới đây.<br/>
<br/>
1. Thông tin cá nhân được lưu giữ khi thành viên hủy tài khoản<br/>
- Thông tin lưu giữ: Họ tên, mã số đăng ký kinh doanh, ID, địa chỉ email, số điện thoại di động, v.v. do thành viên cung cấp<br/>
- Căn cứ lưu giữ: Ngăn chặn người dùng vi phạm đăng ký lại, giải quyết tranh chấp xâm phạm quyền lợi như phỉ báng danh dự và hợp tác điều tra<br/>
- Thời gian lưu giữ: 1 năm kể từ khi thành viên hủy tài khoản<br/>
<br/>
2. Trường hợp cần lưu giữ theo quy định của các văn bản pháp luật liên quan như Luật Thương mại, Luật Bảo vệ người tiêu dùng trong thương mại điện tử, v.v., Công ty sẽ lưu giữ thông tin thành viên trong thời hạn nhất định theo quy định của pháp luật liên quan. Trong trường hợp này, Công ty chỉ sử dụng thông tin được lưu giữ cho mục đích lưu giữ, và thời gian lưu giữ như sau.<br/>
- Hồ sơ về hợp đồng hoặc rút lại đề nghị giao kết hợp đồng<br/>
  ㆍLý do lưu giữ: Luật Bảo vệ người tiêu dùng trong thương mại điện tử<br/>
  ㆍThời gian lưu giữ: 3 năm<br/>
<br/>
- Hồ sơ về thanh toán và cung cấp hàng hóa<br/>
  ㆍLý do lưu giữ: Luật Bảo vệ người tiêu dùng trong thương mại điện tử<br/>
  ㆍThời gian lưu giữ: 3 năm<br/>
<br/>
- Hồ sơ về xử lý khiếu nại hoặc tranh chấp của người tiêu dùng<br/>
  ㆍLý do lưu giữ: Luật Bảo vệ người tiêu dùng trong thương mại điện tử<br/>
  ㆍThời gian lưu giữ: 3 năm<br/>
<br/>
- Hồ sơ truy cập (lịch sử sử dụng dịch vụ, nhật ký truy cập, thông tin IP truy cập, v.v.)<br/>
  ㆍLý do lưu giữ: Luật Bảo vệ bí mật thông tin liên lạc<br/>
  ㆍThời gian lưu giữ: 3 năm<br/>
