
<h3>隐私政策</h3>
<br/>
<br/>
<b>第一条 个人信息的收集与使用目的</b><br/>
<br/>
本公司收集的个人信息将用于以下目的。<br/>
<br/>
1. 履行服务提供相关合同及服务费用结算<br/>
提供内容、商品配送或账单发送、身份验证及购买、费用支付及收取<br/>
<br/>
2. 会员管理<br/>
用于会员服务的身份确认、个人识别、确认注册意愿、限制注册及注册次数、对本修订前注册的 14 岁以下用户进行法定代理人身份确认及后续确认、争议调解记录保存、投诉处理及通知事项传达<br/>
<br/>
3. 用于营销及广告<br/>
用于新服务（产品）的开发与差异化、根据人口统计特征提供服务及投放广告、分析访问频率、统计会员服务使用情况，以及发送活动等广告性信息（会员的个人信息不会提供给委托广告的个人或团体）。<br/>
<br/>
<br/>
<b>第二条 个人信息的收集项目及收集方式</b><br/>
<br/>
【收集的个人信息项目】<br/>
1. 在首次会员注册时，为了用户识别及提供优化服务，将收集以下信息。<br/>
- 必填项目：姓名/企业名称、电子邮箱地址、手机号码、注册认证信息<br/>
<br/>
2. 在修改个人信息时，为了方便服务使用，会员可自愿提供以下信息。<br/>
- 地址、电话号码（服务运营所必需的信息）<br/>
<br/>
3. 在服务使用、活动参与或其他业务处理过程中，可能会生成并收集以下信息。<br/>
- 姓名、实名认证值、i-PIN 编号（使用 i-PIN 认证时）、性别、出生日期、职业、公司名称、地址、电话号码、服务使用记录、访问日志、Cookie、IP 地址、支付记录、不当使用记录、用户状态信息、访问时间<br/>
<br/>
【收集方式】<br/>
本公司通过以下方式收集个人信息。<br/>
<br/>
1. 通过官网会员注册、公告栏、活动报名<br/>
<br/>
2. 用户在使用服务过程中自愿提供<br/>
<br/>
<br/>
<b>第三条 个人信息的保存及使用期限</b><br/>
<br/>
原则上，在达成个人信息收集及使用目的后，将立即删除相关信息。<br/>
但以下信息将基于下述原因在规定期限内予以保存。<br/>
<br/>
1. 会员注销时保存的个人信息<br/>
- 保存项目：会员提供的姓名、营业执照号码、账号、电子邮箱地址、手机号码等<br/>
- 保存依据：防止不当用户重新注册、名誉侵权等权利侵害纠纷处理及调查协助<br/>
- 保存期限：会员注销后 1 年<br/>
<br/>
2. 根据《商法》《电子商务等消费者保护法》等相关法律法规需要保存的，公司将在法律规定的期限内保存会员信息。在此情况下，公司仅将所保存的信息用于其保存目的，保存期限如下。<br/>
- 合同或撤销订购相关记录<br/>
  ㆍ保存原因：《电子商务等消费者保护法》<br/>
  ㆍ保存期限：3 年<br/>
<br/>
- 付款及商品等供应相关记录<br/>
  ㆍ保存原因：《电子商务等消费者保护法》<br/>
  ㆍ保存期限：3 年<br/>
<br/>
- 消费者投诉或争议处理记录<br/>
  ㆍ保存原因：《电子商务等消费者保护法》<br/>
  ㆍ保存期限：3 年<br/>
<br/>
- 访问记录（服务使用记录、访问日志、IP 地址信息）<br/>
  ㆍ保存原因：《通信秘密保护法》<br/>
  ㆍ保存期限：3 年<br/>
